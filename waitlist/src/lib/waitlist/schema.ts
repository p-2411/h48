import { z } from "zod";

/**
 * Field a person never sees. Bots that fill every input fill this too. The name is deliberately
 * meaningless so browser autofill (which matches words like "company" or "website") leaves it empty.
 */
export const HONEYPOT_FIELD = "rf_hp_x7";

export const HOME_TYPES = ["rent", "own", "apartment"] as const;
export type HomeType = (typeof HOME_TYPES)[number];

export const HOME_TYPE_LABELS: Record<HomeType, string> = {
  rent: "I rent",
  own: "I own",
  apartment: "Apartment",
};

// Australian postcodes are four digits (0200–9999 in practice; leading zero for NT/ACT).
const POSTCODE = /^\d{4}$/;

// Referral codes are generated by us: 8 characters of Crockford base32.
const REFERRAL_CODE = /^[0-9A-HJKMNP-TV-Z]{8}$/;

export const emailSchema = z
  .string()
  .trim()
  .min(1, "Enter your email address.")
  .max(254, "That email address is too long.")
  .pipe(z.email("Enter an email address, like sam@example.com."))
  .transform((value) => value.toLowerCase());

export const referralCodeSchema = z
  .string()
  .trim()
  .toUpperCase()
  .regex(REFERRAL_CODE);

export const joinSchema = z.object({
  email: emailSchema,
  referredBy: referralCodeSchema.optional().catch(undefined),
  utmSource: z.string().trim().max(100).optional().catch(undefined),
  utmMedium: z.string().trim().max(100).optional().catch(undefined),
  utmCampaign: z.string().trim().max(100).optional().catch(undefined),
  landingPath: z.string().trim().max(300).startsWith("/").optional().catch(undefined),
  referrer: z.url().max(500).optional().catch(undefined),
});
export type JoinInput = z.infer<typeof joinSchema>;

export const detailsSchema = z.object({
  token: z.string().min(20).max(200),
  homeType: z.enum(HOME_TYPES, { error: "Choose the option that fits your home." }),
  postcode: z.string().trim().regex(POSTCODE, "Enter your 4-digit postcode."),
});
export type DetailsInput = z.infer<typeof detailsSchema>;

/** Reads a FormData field as a string, or undefined when missing or empty. */
export function field(formData: FormData, name: string): string | undefined {
  const value = formData.get(name);
  if (typeof value !== "string") return undefined;
  return value === "" ? undefined : value;
}
